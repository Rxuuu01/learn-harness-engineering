import { afterEach, expect, test } from 'vitest';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { PersistenceService } from './persistence-service';
import { DocumentService } from './document-service';
import { IndexingService } from './indexing-service';
import { QaService } from './qa-service';

const roots: string[] = [];
afterEach(() => { for (const root of roots.splice(0)) fs.rmSync(root, { recursive: true, force: true }); });
test('imports, indexes, restores history, and removes deleted documents from retrieval', async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'knowledge-test-'));
  roots.push(root);
  const source = path.join(root, 'notes.md');
  fs.writeFileSync(source, '知识库设计采用本地存储。 Architecture uses local storage.');
  const data = path.join(root, 'data');
  const persistence = new PersistenceService(data);
  expect(fs.existsSync(path.join(data, 'documents'))).toBe(true);
  const documents = new DocumentService(persistence);
  const first = documents.importDocument(source);
  const second = documents.importDocument(source);
  expect(fs.readdirSync(persistence.getDocumentsDir())).toHaveLength(2);
  const index = new IndexingService(persistence);
  await index.startIndexing(first.id);
  expect(documents.getDocument(first.id)?.status).toBe('indexed');
  await index.startIndexing();
  expect(index.getStatus().indexStatus).toBe('ready');
  const qa = new QaService(persistence);
  expect((await qa.ask('知识库设计')).citations.length).toBeGreaterThan(0);
  expect(new QaService(new PersistenceService(data)).getHistory()).toHaveLength(1);
  documents.deleteDocument(first.id);
  expect(index.getAllChunks().every(c => c.documentId !== first.id)).toBe(true);
  expect(fs.existsSync(source)).toBe(true);
  expect(fs.readdirSync(persistence.getDocumentsDir())).toHaveLength(1);
  documents.deleteDocument(second.id);
  expect((await qa.ask('architecture')).citations).toHaveLength(0);
  await expect(qa.ask(' ')).rejects.toThrow();
});
